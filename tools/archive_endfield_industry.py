"""Select a small industrial reference kit and archive its dependency closure.

Original VFS chunks are read-only. MD5 validates each raw bundle; SHA256 and
ownership records distinguish recovered bundles from converted/unverified assets.
No files are copied into Mod/Assets or the authored model project.
"""
from pathlib import Path
import argparse
from collections import Counter
import hashlib
import json
import re

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT/'local/endfield/industry-library'
PC = 'assets/beyond/dynamicassets/gameplay/factory/ciautogenerated/pc/'
MACHINES = ['power_diffuser_1', 'power_pole_2', 'power_station_1', 'power_port_1',
            'miner_2', 'furnance_1', 'grinder_1', 'shaper_1', 'component_mc_1',
            'tools_assebling_mc_1', 'storager_1', 'loader_1', 'unloader_1']


def read(p):
    return json.loads(p.read_text(encoding='utf-8-sig'))


def write(p, value):
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(value, ensure_ascii=False, indent=2), encoding='utf-8')


def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--extract', action='store_true')
    args=ap.parse_args()
    manifest=read(ROOT/'local/endfield/manifest-index.json')
    vfs=read(ROOT/'local/endfield/vfs-index.json')
    buildings=read(ROOT/'local/endfield/tower-library/tables-raw/Table/FactoryBuildingTable.json')
    labels=read(ROOT/'local/endfield/tower-library/tables-raw/Table/I18nTextTable_CN.json')
    paths={a['path']:a for a in manifest['assets']}
    bundles={b['index']:b for b in manifest['bundles']}
    files={f['fileName'].lower():f for f in vfs['files']}
    groups={}
    for key in MACHINES:
        b=buildings[key]
        render=b['rendererTemplateMap'][b['defaultRendererTemplate']]
        ids={render['machineRenderId'],render['logisticBaseUnit'],render['nonLogisticBaseUnit']}
        seeds={PC+'building/'+i+'.asset' for i in ids if PC+'building/'+i+'.asset' in paths}
        # Exact item/port identities, not broad matches for all factory decoration.
        seeds.update(p for p in paths if '/sprites/' in p and re.search(r'(?:item_port_|image_|icon_port_)'+re.escape(key)+r'\.png$',p))
        groups[key]=dict(name=labels.get(str(b['name']['id'])), seeds=sorted(seeds), building=b)
    groups['logistics']=dict(name='传送带、分流、汇流、桥接', seeds=sorted(p for p in paths if
        p.startswith(PC) and re.search(r'/(?:grid_belt_01_\w+|log_(?:splitter|converger|connector)(?:_\d+)?|conveyor_repeater_simple)\.asset$',p)
        or p.endswith('/factory/common/conveyor_instancing_template.prefab')))
    groups['batteries']=dict(name='五级电池图标/物品参照',seeds=sorted(p for p in paths if re.search(r'(?:/|_)item_proc_battery_[1-5]\.png$',p)))
    groups['placement-range-candidates']=dict(name='范围/占地预览候选，未证明全部用于炮塔攻击范围',seeds=sorted(p for p in paths if
        '/gameplay/factory/common/' in p and p.endswith('.prefab')
        or p.endswith(('/p_common_rangecircle_01.prefab','/vfxdecalfactory.shader','/t_fac_com_grid_atlas.png','/t_cell_grid.png'))))
    battle=read(ROOT/'local/endfield/tower-library/tables-raw/Table/FactoryBattleTable.json')
    effects={b['attackRangeEffect'].lower() for b in battle.values() if b.get('attackRangeEffect')}
    groups['attack-range-confirmed']=dict(name='FactoryBattleTable.attackRangeEffect 直接引用的圆形/矩形范围',
        evidence={k:v['attackRangeEffect'] for k,v in battle.items() if v.get('attackRangeEffect')},
        seeds=sorted(p for p in paths if '/effects/prefabs/' in p and Path(p).stem in effects))
    owners={}
    for key,g in groups.items():
        if not g['seeds']:
            raise ValueError('Empty group: '+key)
        todo=[paths[p]['bundle'] for p in g['seeds']]
        seen=set()
        while todo:
            bid=todo.pop()
            if bid in seen: continue
            seen.add(bid)
            todo.extend(bundles[bid]['dependencies'])
        g['bundles']=sorted(seen)
        for bid in seen: owners.setdefault(bid,[]).append(key)
    rows=[]
    for bid in sorted(owners):
        b=bundles[bid]
        f=files.get(('Data/Bundles/Windows/'+b['name']).lower())
        if f is None: raise ValueError('Missing VFS bundle: '+b['name'])
        rel='raw-bundles/'+b['name']
        row=dict(bundle=bid,name=b['name'],file=rel,bytes=f['length'],owners=owners[bid],vfs=f,status='indexed')
        if args.extract:
            if f['encrypted']: raise ValueError('Unexpected encrypted bundle: '+b['name'])
            with Path(f['chunkAbsolutePath']).open('rb') as stream:
                stream.seek(f['offset']); payload=stream.read(f['length'])
            if len(payload)!=f['length'] or hashlib.md5(payload).digest()!=bytes.fromhex(f['fileDataMd5'])[::-1]:
                raise ValueError('Source MD5 mismatch: '+b['name'])
            dest=OUT/rel
            if not dest.resolve().is_relative_to(OUT.resolve()): raise ValueError(rel)
            dest.parent.mkdir(parents=True,exist_ok=True)
            if dest.exists() and dest.read_bytes()!=payload: raise ValueError('Changed output: '+str(dest))
            dest.write_bytes(payload)
            row.update(status='extracted-md5-verified',sha256=hashlib.sha256(payload).hexdigest())
        rows.append(row)
    assets=[dict(a,owners=owners[a['bundle']]) for a in manifest['assets'] if a['bundle'] in owners]
    summary=dict(groups=len(groups),bundles=len(rows),assets=len(assets),bytes=sum(r['bytes'] for r in rows))
    write(OUT/'catalog.json',dict(stage='original bundles; conversion and scene assembly are separate',
        manifestVersion=manifest['version'],manifestHash=manifest['hash'],groups=groups,bundles=rows,assets=assets,summary=summary))
    print(json.dumps(summary))


if __name__ == '__main__':
    main()
