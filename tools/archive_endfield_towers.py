"""Archive Endfield defense families with dependency and provenance records.

Only reads the installed VFS. Raw bundles are MD5-checked before archiving;
converted exports remain separate from original bundles and runtime adaptations.
"""
from __future__ import annotations

import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
LIB = ROOT / 'local/endfield/tower-library'


def read(path):
    return json.loads(Path(path).read_text(encoding='utf-8-sig'))


def write(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding='utf-8')


def category(path):
    if '/effects/' in path:
        return 'effects'
    if '/gamedata/' in path:
        return 'combat-config'
    if '/animations/' in path or '_vat.' in path:
        return 'animation-vat'
    if '/sprites/' in path:
        return 'ui'
    if path.endswith(('.mat', '.shader')):
        return 'materials-shaders'
    if path.endswith(('.png', '.tga', '.exr')):
        return 'textures'
    if 'lod' in path or 'models/' in path or '_col' in path:
        return 'models-colliders'
    return 'assembly-config'


def collect(extract=False):
    manifest = read(ROOT / 'local/endfield/manifest-index.json')
    vfs = read(ROOT / 'local/endfield/vfs-index.json')
    tables = LIB / 'tables-raw/Table'
    buildings = read(tables / 'FactoryBuildingTable.json')
    labels = read(tables / 'I18nTextTable_CN.json')
    battle = read(tables / 'FactoryBattleTable.json')
    audio = read(tables / 'AudioBattleBuildings.json')
    audio_factory = read(tables / 'AudioFactory.json')
    bundles = {b['index']: b for b in manifest['bundles']}
    paths = {a['path']: a for a in manifest['assets']}
    files = {f['fileName'].lower(): f for f in vfs['files']}
    owners, families = {}, {}
    for key, building in buildings.items():
        if not key.startswith('battle_'):
            continue
        render = building['rendererTemplateMap'][building['defaultRendererTemplate']]
        render_id = render['machineRenderId']
        root_path = 'assets/beyond/dynamicassets/gameplay/factory/ciautogenerated/pc/building/' + render_id + '.asset'
        seeds = {root_path} if root_path in paths else set()
        # Explicit factory identity avoids matching unrelated enemy cannon weapons.
        stem = key.removeprefix('battle_')
        for p in paths:
            if (re.search(re.escape(render_id) + r'(?:[_./]|$)', p)
                    or ('/gamedata/' in p and re.search(r'int_fac_(?:battle_)?' + re.escape(stem) + r'(?:[_./]|$)', p))
                    or ('/effects/' in p and re.search(r'battle_' + re.escape(stem.rsplit('_', 1)[0]) + r'\+' + re.escape(stem.rsplit('_', 1)[-1]) + r'_', p))):
                seeds.add(p)
        todo = [paths[p]['bundle'] for p in seeds]
        owned = set()
        while todo:
            bid = todo.pop()
            if bid in owned:
                continue
            owned.add(bid)
            todo.extend(bundles[bid]['dependencies'])
        for bid in owned:
            owners.setdefault(bid, []).append(key)
        entry = dict(id=key, nameCN=labels.get(str(building['name']['id'])),
                     nameTextId=str(building['name']['id']), renderId=render_id,
                     seeds=sorted(seeds), bundles=sorted(owned), building=building,
                     combat=battle.get(key), audioEvents=audio.get(key),
                     factoryAudio=audio_factory.get(key),
                     nameEvidence='FactoryBuildingTable.name.id -> I18nTextTable_CN',
                     missingRoot=root_path if root_path not in paths else None)
        families[key] = entry

    rows, missing = [], []
    for bid in sorted(owners):
        bundle = bundles[bid]
        f = files.get(('Data/Bundles/Windows/' + bundle['name']).lower())
        if f is None:
            missing.append(dict(bundle=bid, name=bundle['name']))
            continue
        rel = 'raw-bundles/' + bundle['name']
        row = dict(bundle=bid, name=bundle['name'], owners=owners[bid], file=rel,
                   bytes=f['length'], vfs=f, status='indexed')
        if extract:
            if f['encrypted']:
                raise ValueError('Encrypted bundle requires the VFS decoder: ' + f['fileName'])
            with Path(f['chunkAbsolutePath']).open('rb') as stream:
                stream.seek(f['offset'])
                payload = stream.read(f['length'])
            digest = hashlib.md5(payload).hexdigest()
            # VFS exposes the 128-bit hash integer in reverse byte order.
            expected = bytes.fromhex(f['fileDataMd5'])[::-1].hex()
            if len(payload) != f['length'] or digest != expected:
                raise ValueError('VFS extent/hash mismatch: ' + f['fileName'])
            target = LIB / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            if target.exists() and target.read_bytes() != payload:
                raise ValueError('Refuse to overwrite different archive bytes: ' + str(target))
            target.write_bytes(payload)
            row.update(status='extracted-md5-verified', sha256=hashlib.sha256(payload).hexdigest())
        rows.append(row)
    assets = [dict(a, category=category(a['path']), owners=owners[a['bundle']])
              for a in manifest['assets'] if a['bundle'] in owners]
    for key, family in families.items():
        family['assets'] = [a for a in assets if key in a['owners']]
        write(LIB / 'families' / key / 'catalog.json', family)
    result = dict(schemaVersion=1, sourceGame='Arknights Endfield local Windows installation',
                  manifestVersion=manifest['version'], manifestHash=manifest['hash'],
                  stage='raw archive; converted outputs separate; not runtime integration',
                  families=[dict(id=f['id'], nameCN=f['nameCN'], renderId=f['renderId'],
                                 seedCount=len(f['seeds']), bundleCount=len(f['bundles'])) for f in families.values()],
                  bundles=rows, assets=assets, missing=missing,
                  categories=dict(Counter(a['category'] for a in assets)))
    write(LIB / 'catalog.json', result)
    write(LIB / 'audio-cues.json', {
        'status': 'cue IDs archived; Wwise media conversion is a separate step',
        'sourceTables': ['AudioBattleBuildings.json', 'AudioFactory.json'],
        'families': {key: {'nameCN': value['nameCN'], 'audioEvents': value['audioEvents'],
                           'factoryAudio': value['factoryAudio']}
                     for key, value in families.items() if value['audioEvents'] or value['factoryAudio']}
    })
    print(json.dumps(dict(families=len(families), bundles=len(rows), assets=len(assets),
                          bytes=sum(r['bytes'] for r in rows), missing=missing), ensure_ascii=False))


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--extract', action='store_true')
    collect(parser.parse_args().extract)
