"""Build the .scmod archive with a complete asset and hash inventory.

Recipes: Assets/MechDefense.cr. Towers: Assets/Towers (generated by build_tower_assets.py, make_fx_atlas.py).
Tower audio mixes: Assets/Imported/Endfield/Audio. Mercury, the mech: Assets/Imported/Mercury (tools/build_mech_assets.py).
The 0.5.0 Destroy Gunners sample assets (mech/enemy models, icons, motion catalogue, fire sound) must not come back into
the package (checked below). Since 0.9.0: the robot enemies (Assets/Imported/RD05, RD06, RD07, RD17 from
tools/build_unit_assets.py, checked like Mercury's) and the progression item models (Assets/Parts, tools/build_part_models.py).
Mod settings: one entry in modinfo.json "Settings" opens the mod's own page (Mod/MDSettingsScreen.cs).
The mech and robot models (Assets/Imported/*/*.glb) get their embedded PNG textures re-encoded as WebP quality 90
(tools/webp_glb.py, EXT_texture_webp), and so do their icon textures (Imported/*/icon.png -> icon.webp). Textures the mod
loads by name without an extension ship as lossless WebP: tower atlases, Towers/fx, Parts/parts (tools/package_formats.py).
Tower slot pictures (icon.png, opened by file name) stay PNG. The source files stay PNG.
"""
from pathlib import Path
import hashlib,json,zipfile,subprocess,sys
root=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(root/'tools'))
from webp_glb import webp_glb   # noqa: E402
from package_formats import webp   # noqa: E402
subprocess.run(['dotnet','build',str(root/'Mod/MechDefense.csproj'),'-c','Release','--nologo'],check=True)
assets=root/'Mod/Assets'
files=[(root/'Mod/bin/Release/net10.0/MechDefense.dll','MechDefense.dll'),(root/'Mod/modinfo.json','modinfo.json'),(assets/'MechDefense.xdb','Assets/MechDefense.xdb')]
files.append((assets/'MechDefense.cr','Assets/MechDefense.cr'))   # crafting recipes (the API merges every .cr in the package)
towers=json.loads((assets/'Towers/towers.json').read_text(encoding='utf-8'))['towers']
files+=[(assets/'Towers/towers.json','Assets/Towers/towers.json'),(assets/'Towers/fx.png','Assets/Towers/fx.png')]
files.append((assets/'Towers/status.png','Assets/Towers/status.png'))   # 0.15.0 damage-type and status icons (tools/build_status_icons.py, MDElements)
for t in towers:
    # icon.png: the slot picture (tools/render_tower_icons.py, rerun after any tower rebuild); icon.bin: the dropped item
    for f in ['model.glb','atlas.png','icon.bin','icon.png']:
        p=assets/'Towers'/t['id']/f;assert p.exists(),p;files.append((p,f'Assets/Towers/{t["id"]}/{f}'))
sounds={s for t in towers for k in ('fireSounds','hitSounds','chargeSounds') for s in t.get(k,[])}
for s in sorted(sounds):
    if s.startswith('Imported/'):
        p=assets/(s+'.ogg');assert p.exists(),p;files.append((p,'Assets/'+s+'.ogg'))
mercury=assets/'Imported/Mercury';mech=json.loads((mercury/'mech.json').read_text(encoding='utf-8'))
assert (mercury/'clips.bin').stat().st_size==4*8*len(mech['joints'])*sum(c['samples'] for c in mech['clips']),'clips.bin does not match mech.json'
assert max(c['p99_m'] for c in mech['check'])<1e-3,'mech assets failed their re-pose check'
for f in ['model.glb','mech.json','clips.bin','icon.bin','icon.png']+[f'Audio/{k}.ogg' for k in mech['sounds']]:files.append((mercury/f,f'Assets/Imported/Mercury/{f}'))
# hero mechs 复仇女神 / 轩辕十四 (Mod/MDMech.cs MDMechType, tools/build_hero_assets.py): Mercury's format; their sounds are Mercury's
for hero in ['Nemesis','Regulus']:
    d=assets/'Imported'/hero;h=json.loads((d/'mech.json').read_text(encoding='utf-8'))
    assert (d/'clips.bin').stat().st_size==4*8*len(h['joints'])*sum(c['samples'] for c in h['clips']),f'{hero} clips.bin does not match mech.json'
    assert {'turret','armL','armR','cannon','firstPerson','grenade'}<=set(h['roles']),f'{hero} mech.json roles'
    for f in ['model.glb','mech.json','clips.bin','icon.bin','icon.png']:files.append((d/f,f'Assets/Imported/{hero}/{f}'))
# progression items (Mod/MDParts.cs): texture atlas and 3D models (tools/build_part_models.py, committed)
parts=assets/'Parts';files.append((parts/'parts.png','Assets/Parts/parts.png'))
for n in range(9):p=parts/f'part{n}.bin';assert p.exists(),p;files.append((p,f'Assets/Parts/part{n}.bin'))
# mod settings (Mod/MDSettingsScreen.cs): one entry in the game's list that opens the mod's own page
settings=json.loads((root/'Mod/modinfo.json').read_text(encoding='utf-8')).get('Settings')
assert settings and settings[0]['Items'][0]['Widget']=='Game.MDSettingsEntryWidget','modinfo.json Settings'
# robot enemies (Mod/MDRobots.cs, tools/build_unit_assets.py): same checks as Mercury's assets
# 0.14.0: our own v3 units (tools/stage_v3_units.py from E:/projects/dguns-enemy-models/v3_new) carry their own checks
# (checks/SUMMARY.json all_ok, or gates missed and accepted in stage_v3_units.ACCEPTED) instead of the re-pose numbers of
# build_unit_assets.py
for unit in ['RD05','RD06','RD07','RD17','RD14','RD09','EN02','RD13','RD21','RD08','RD19']:
    d=assets/'Imported'/unit;u=json.loads((d/'unit.json').read_text(encoding='utf-8'))
    assert (d/'clips.bin').stat().st_size==4*8*len(u['joints'])*sum(c['samples'] for c in u['clips']),f'{unit} clips.bin does not match unit.json'
    if (d/'v3_checks.json').exists():v3=json.loads((d/'v3_checks.json').read_text(encoding='utf-8'));assert v3.get('all_ok') is True or v3.get('accepted'),f'{unit} v3 checks failed'
    else:
        checks=u.get('check') or []
        assert checks and max(c['p99_m'] for c in checks)<1e-3,f'{unit} assets failed their re-pose check'
    for s in u.get('skins') or ['model']:files.append((d/f'{s}.glb',f'Assets/Imported/{unit}/{s}.glb'))
    for f in ['unit.json','clips.bin','icon.bin','icon.png']:files.append((d/f,f'Assets/Imported/{unit}/{f}'))   # icon: the creative summon item (MDSummon.cs)
# the robots' and the boss's sounds are Mercury's (MDRobots.Sound -> MDMechBrain.Se): already in the package above
assert {f'se{i:02d}' for i in (7,8,9,10,11,13,14,20,24,25,31)}<=set(mech['sounds']),'a robot sound is missing from Mercury\'s audio'
removed=('Assets/Imported/Mech/','Assets/Imported/Enemy/','Assets/Imported/Audio/Fire','Assets/Animations/','Assets/Towers/_legacy/')
assert not [n for _,n in files if n.startswith(removed)],'Destroy Gunners assets in the package'
# by name: tower atlases, the effect sprites and the item atlas lossless; the mech and robot icon textures quality 90
WEBP_LOSSLESS=lambda n:n.startswith('Assets/Towers/') and n.endswith('/atlas.png') or n in ('Assets/Towers/fx.png','Assets/Parts/parts.png')
WEBP_LOSSY=lambda n:n.startswith('Assets/Imported/') and n.endswith('/icon.png')
files=[(p,n[:-4]+'.webp' if WEBP_LOSSLESS(n) or WEBP_LOSSY(n) else n) for p,n in files]
def content(p,n):
    if n.startswith('Assets/Imported/') and n.endswith('.glb'):return webp_glb(p.read_bytes(),90)
    if n.endswith('.webp'):return webp(p,lossless=not (n.startswith('Assets/Imported/') and n.endswith('/icon.webp')))
    return p.read_bytes()
data={n:content(p,n) for p,n in files}
manifest=[dict(path=n,bytes=len(data[n]),sha256=hashlib.sha256(data[n]).hexdigest()) for p,n in files]
out=root/'dist';out.mkdir(exist_ok=True)
version=json.loads((root/'Mod/modinfo.json').read_text(encoding='utf-8'))['Version']
package=out/f'MechDefense-{version}.scmod'
with zipfile.ZipFile(package,'w',zipfile.ZIP_DEFLATED) as z:
    for p,n in files:z.writestr(zipfile.ZipInfo.from_file(p,n),data[n],zipfile.ZIP_DEFLATED)
    z.writestr('asset-manifest.json',json.dumps(manifest,indent=2))
(out/'package-manifest.json').write_text(json.dumps(manifest,indent=2))
print('Package:',package,'bytes:',package.stat().st_size,'files:',len(files))
